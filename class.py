text = "Зима в этом году началась неожиданно рано. Снег укрыл город плотным белым одеялом, и деревья замерли в ожидании тепла. Люди спешат домой, укутавшись в шарфы, а в окнах домов загораются уютные огни.\nГорячий чай согревает руки и мысли, пока книги на полках ждут своего часа. Вечера становятся длиннее и спокойнее, ведь важно находить радость в мелочах. \nКаждый день приносит свои маленькие открытия, и нужно беречь моменты тишины. Снежинки танцуют за стеклом в бесконечном вальсе, предвещая скорые праздники.\nГлавное — сохранять тепло в душе, ведь мир вокруг нас меняется к лучшему, надо просто уметь это замечать.\nВпереди много новых и важных дел, и жизнь продолжается, несмотря на любые холода."

text_length = len(text)
text_words = len(text.split(" "))
text_lines_req = text_length // 100 + 1
print(text_length, text_words, text_lines_req)
slicer_a = 0
slicer_b = 100

for i in range(text_lines_req):
    s = str(i) + ". " + text[slicer_a:slicer_b].strip()
    s.strip()
    slicer_a += 100
    slicer_b += 100
    print(s)